/**
 * 记一笔 · 导入模板（2026-09-18）—— 把「契约」做成**能发给电脑的文件**。
 *
 * 为什么要有文件版：「复制契约示例」只能把文本留在手机的剪贴板里，而外部 AI 多半在电脑上。
 * 所以这里在本机生成两份模板，由用户**转发到聊天**（文件传输助手 / 电脑）——
 * 全程不经过后端、不上传，与「导入文件」本机解析是同一条隐私口径。
 *
 * 两份模板的写法不同、**字段完全一样**（与 utils/fileImport.ts 的解析器三方对齐，改一处要一起改）：
 *   .json —— 字段名与表单一一对应，外部 AI 照它填最不容易出错（推荐）；
 *   .md   —— 「字段：值」逐行，「正文：」以下全算正文；人也能直接照着填。
 * 唯一的差别是 md 没有 `contentHtml`：正文按 md 语法写就行，读进来会自动转富文本。
 *
 * 两点约定：
 *  1. **文案上不出现「下载」**：微信里没有下载落点，落点就是"转发到聊天"
 *     （底层用 localBackup 的 writeTextFile + shareFile，与备份 / 修行档案导出同一套）；
 *  2. **文件名的 ASCII 惯例**：与 guanzhi-backup-*、guanzhi-archive-* 一致，
 *     避开多字节文件名在各端转发时的差异。
 */
import { shareFile, writeTextFile } from '@/utils/localBackup'

/** 模板格式：json（契约最准）/ md（人和 AI 都能填） */
export type TemplateKind = 'json' | 'md'

/**
 * 契约示例（JSON）—— 记一笔的**全部字段，只剔掉三格**。
 *
 * 口径（2026-09-18 定，用户两轮校正后）：
 *   契约 = 这一笔的全部表单字段 − 归属（kind）/ 主题（topics）/ 标签（tags）。
 * 为什么不给外面这三格：**原文里并没有写着"这是理"** —— 归类是读者的事。
 * AI 替你归，等于把你第一次读它的判断整段跳过；而这三格在应用里点一下就有，
 * 反过来让 AI 猜、猜错还要改，得不偿失。
 *
 * 注意：**「你的话」六格（经典语句 / 摘要 / 重要观点 / 一句话总结 / 感悟 / 为什么成立）在契约里**。
 * 理由不是"AI 该替你想"，而是**导入只是预填**：回填进来的每一格都要你过一遍、
 * 最后那一下「存入收件匣」永远由你按（页面提示条也这么写）。所以允许 AI 先起一版草稿，
 * 但**不代存**这条线不能松 —— 松了才是真的把"读过写下才算数"架空。
 *
 * JSON 不能写注释，所以每格的"这里要什么"只能写在**值**里 —— 值本身就是给 AI 的说明，
 * 它会照形状替换掉。MD 模板（CONTRACT_MD）用**同一套字段**，只是换成「字段：值」的写法。
 * 改字段名要与 utils/fileImport.ts、后端 parseService 一起改。
 */
export const CONTRACT_JSON = `{
  "form": "文章 / 一句话 / 视频 三选一",
  "title": "给它起一个你以后找得回来的标题",
  "sourceName": "它从哪来：公众号 / 播客 / 书 / 朋友 / UP 主",
  "link": "原文链接；没有就留空",
  "videoUrl": "视频链接（形态选「视频」才填）；没有就留空",
  "golden": ["从原文里挑出最打动你的那句话（可多条）"],
  "digest": "用你自己的话把原文压成两三句",
  "viewpoints": [{ "title": "一句话结论", "text": "解释 / 证据；可多条，一条一个对象" }],
  "summary": "一句话说清它讲了什么（这一格必填）",
  "insight": "它让你想到什么、你打算怎么用",
  "why": "它在什么条件下成立、反例是什么（只有归到「理」才需要，拿不准就留空）",
  "content": "原文正文：把原文照抄进来（是原文，不是你的总结）",
  "contentHtml": "<p>同一份正文的带样式版本（可选）：可用 <strong>加粗</strong>、<h3>小标题</h3>、<ul><li>列表</li></ul></p>"
}`

/**
 * 模板（Markdown）—— 值**全部留空**，给人 / AI 填；**字段与 JSON 契约完全一样**。
 *
 * 四条规则（都对应解析器的行为，别改坏）：
 *  1. 值写在冒号后面；空值会被忽略，所以留空的行等于没写，不会把空字段灌进表单；
 *  2. **字段名后面可以带括号注**（「重要观点（一行一条）：」）—— 解析器会剥掉行尾括号再认字段，
 *     注里写清"这格要什么"最省事；但**注里不能出现冒号**（冒号是名与值的分界）；
 *  3. 「提示」行、`##` 标题行都只写给人看：认不出字段名的整行跳过；
 *  4. 「正文：」之后**直到文件结束**都算正文，所以它必须放在最后一个字段。
 *
 * 与 JSON 唯一的差别：**没有 `contentHtml` 这一格** —— md 的正文本身支持
 * `#` / `**` / `-` / `>`，读进来会自动转成富文本，用不着再手写一遍 HTML。
 * 归属 / 主题 / 标签两边都不在契约里（原因见 CONTRACT_JSON 的注释），所以模板里也不列。
 */
export const CONTRACT_MD = `# 观止知行 · 记一笔导入模板

提示：把值写在冒号后面；用不着的行整行删掉（空值会被忽略，不会写进表单）。
提示：括号里的字是说明，不用删；「正文」必须放在最后一个字段 —— 它以下直到文件结束都算正文。
提示：正文支持简单格式：# 小标题、**加粗**、- 列表、> 引用（会自动转成富文本，所以没有单独的一格）。
提示：这份模板没有 归属（事 / 理 / 道）、主题、标签 —— 那三格是你给这条内容归的类，不在契约里。

形态（文章 / 一句话 / 视频）：
标题（你以后找得回来的名字）：
来源（公众号 / 播客 / 书 / 朋友）：
链接（原文地址；没有就留空）：
视频链接（形态选「视频」才填）：
经典语句（从原文里挑出最打动你的那句；可多条，用、隔开）：
摘要（用你自己的话把原文压成两三句）：
重要观点（一行一条，写成「结论 —— 解释 / 证据」）：
一句话总结（一句话说清它讲了什么）：
感悟（它让你想到什么、你打算怎么用）：
为什么成立（什么条件下成立、反例是什么；归到「理」才需要）：

## 正文 · 原文原话，不是你的总结

正文：
`

/** 转发出去的文件名（与备份 / 档案导出的命名惯例一致） */
const TEMPLATE_FILE: Record<TemplateKind, string> = {
  json: 'guanzhi-import-template.json',
  md: 'guanzhi-import-template.md',
}

function templateText(kind: TemplateKind): string {
  return kind === 'json' ? CONTRACT_JSON : CONTRACT_MD
}

/**
 * 生成模板文件并转发到聊天（用户自己发给「文件传输助手」再在电脑上打开）。
 * 失败时**抛出**可读原因（基础库 < 2.16.1 不支持文件转发），由调用方给出降级建议。
 */
export async function shareTemplate(kind: TemplateKind): Promise<void> {
  const { filePath, fileName } = writeTextFile(templateText(kind), TEMPLATE_FILE[kind])
  await shareFile(filePath, fileName)
}
