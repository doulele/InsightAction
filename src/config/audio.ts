/* ------------------------------------------------------------------ *
 * 呼吸干预（4-7-8）：引导方式与节奏
 * ------------------------------------------------------------------ */

/**
 * 一圈里两个切分点（秒）：4 秒处「吸」转「屏」，11 秒处「屏」转「呼」。
 *
 * 页面按**比例**折算（`BREATH_SPLIT / cycle`），所以一圈是 19 秒还是 19.66 秒都对得上 ——
 * 换素材时不必动页面里的相位代码。
 */
export const BREATH_SPLIT = [4, 11] as const

/** 一记模式的一圈秒数（页面自己的 4-7-8 节奏，与素材无关） */
export const BREATH_CUE_CYCLE = 19

/**
 * 连续引导模式的一圈秒数 —— **必须等于素材的实测时长**。
 *
 * 2026-09-22 实测 `呼吸_4-7-8循环.mp3` = 19.66 秒（不是 19.00 秒）。
 * 每圈差 0.66 秒，跑三分钟就错开六秒 —— 声音在说"吸"、界面在说"呼"。
 * 所以这一条与素材绑死：换素材（例如重做成正好 19.00 秒）必须同步改这里。
 */
export const BREATH_TRACK_CYCLE = 19.66

/**
 * 呼吸引导怎么出声：
 *  - `cue`：吸 / 屏 / 呼 各一声一记（`CUE_SOURCES.in / hold / out`），节奏由页面给；
 *  - `track`：一段连续呼吸引导整圈循环（`BREATH_TRACK`），页面相位跟着素材走。
 *
 * 两者只能开一个：一记会抢走唯一的播放实例、把环境音打断（见 `utils/audio.ts` 的
 * `cueBusy`），同时开会变成"声音在吸、屏息起点又叮一声"，两套提示互相拆台。
 *
 * 2026-09-22 定：**默认走 `cue`**。`track` 停在 `'track'` 只活了一天 —— 当天把
 * `呼吸_4-7-8循环.mp3` 逐帧解到 granule 级响度后发现两件事：① 时长 19.66 秒（4-7-8 应 19.00）；
 * ② **7.00–9.25 秒是整段数字静音（约 2.25 秒），位置与长度都对不上 4-7-8 的屏息段**
 * （屏息应落在中段 4.1–11.4 秒，而且做成全静音会让人以为声音断了）。
 * 结论是这一段不是按 4-7-8 做的 —— 要恢复连续引导，先把素材重做成**正好 19.00 秒、
 * 屏息留一层轻底噪、首尾无淡入淡出**，再把这一行改回 `'track'`。
 */
export type BreathGuide = 'cue' | 'track'
export const BREATH_GUIDE: BreathGuide = 'cue'

