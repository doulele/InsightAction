export interface AmbientTrack {
  /**
   * 候选文件，**第一个是理想素材，缺了就往右回落**。
   *
   * 与提示音的候选链同一个思路：链首是专为这一处要的音（2026-09-22 已上线），
   * 链尾是目录里现成的近似音（沙漏「滴答」→ `雨打屋顶`、茶室「煮雪」→ `森林篝火`）。
   * 缺文件时整条链往下走 —— 所以链首可以改名，**链尾那几个现成的别动**。
   */
  files: string[]
  /**
   * 相对音量（0–1）。**各自留一格是为了将来单项微调**，当前一律取 `AMBIENT_VOLUME`
   * —— 归一之后"谁该比谁响"已经由素材拉平了，这里再逐个拍数字只会把统一重新搅乱。
   */
  volume: number
}

export interface AmbientOption {
  id: string
  name: string
  hint: string
  /** 缺省 = 「静」，不下载任何文件 */
  track?: AmbientTrack
}

