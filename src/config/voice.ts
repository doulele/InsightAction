/**
 * 语音转写（「按住说话」）的口径 —— 引擎顺序、录音参数、文案都在这里，页面与 utils 不写死。
 * ================================================
 *
 * **两个引擎，默认插件优先、后端兜底**：
 *
 * | | 插件（微信同声传译） | 后端（`POST /guanzhi/asr`） |
 * | --- | --- | --- |
 * | 识别在哪 | 微信侧 —— **音频不出设备** | 我们的服务器（再转交第三方接口，或本机 whisper） |
 * | 前置 | 后台添加插件 + `manifest.json` 声明 | 服务端配好 ASR 引擎（见后端 `.env.example`） |
 * | 提审 | ⚠️ 插件类目「IT科技-软件服务提供商」对**个人主体**超范围，带着它提审必被驳回 | 不占 `plugins` 声明，**不受这条约束** |
 * | 首字延迟 | 边说边出字 | 松手后 1~3 秒（上传 + 转写） |
 *
 * 顺序由 `VOICE_ENGINE_ORDER` 决定。**为什么默认把插件排在前面**：
 * 插件在的时候（本机调试、真机自测、以及还没删声明的那一版）走它体验最好，而且音频不出设备；
 * 一旦**删掉 `manifest.json` 的 plugins 块**，插件就探不到，代码会自动落到后端那条路 ——
 * 不需要改任何常量，也不需要为此多提一次审。想全程只走后端（自测那条链路）就把顺序倒过来。
 *
 * 这一步带来的隐私口径变化（录音离开手机）见 PRIVACY.md 第 5.1 节。
 */

/** 引擎尝试顺序：写在前面的先试，探不到 / 不可用就交给下一个 */
export const VOICE_ENGINE_ORDER = ['plugin', 'backend'] as const

/**
 * 录音参数（只给后端引擎用；插件引擎的录音由插件自己管，切分段位见官方文档）。
 *
 * 为什么是 mp3 / 16k / 单声道 / 24kbps：语音转写只要人声可辨，16k 单声道足够；
 * 24kbps 让 60 秒只有 ~180KB，**上传快、后端也好收**（体积闸门见后端 config.asr.maxBytes）。
 */
export const RECORD = {
  /** 单次录音上限（毫秒）：与后端 `config/index.js` 的 asr.maxDurationMs 同口径 */
  maxMs: 60000,
  /** 短于它 = 误触，直接按「没听清」处理，不白跑一次上传 */
  minMs: 800,
  sampleRate: 16000,
  numberOfChannels: 1,
  encodeBitRate: 24000,
  format: 'mp3',
} as const

/** 后端那条路的请求超时（毫秒）：local 引擎在弱机器上要几十秒，别用 http 层默认的 15 秒把它掐死 */
export const ASR_TIMEOUT_MS = 90000

/**
 * 插件引擎的识别语言。写法与后端那条路不同（插件要 `zh_CN`、whisper 那类接口要 `zh`），
 * 所以两处**不能复用同一个常量**，改了这里别顺手去改后端 ASR_LANG。
 */
export const PLUGIN_LANG = 'zh_CN'

