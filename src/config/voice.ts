/**
 * 把文案里的 `{x}` 占位符填掉。
 * 存在的意义：**数字也只留一处**（如「最长 60 秒」来自 RECORD.maxMs、截断字数来自页面常量），
 * 免得改了阈值忘了改文案。
 */
export function voiceText(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''))
}
