/**
 * 开屏排班（2026-09-22）：每 `STARTUP_PERIOD` 天一个周期，前
 * `min(自己的道数, STARTUP_DAO_SLOTS)` 天归「我的道」，剩下归这个池子。
 *
 * 为什么需要排班：取用规则原本是三段硬优先序（回响 → 道 → 池子），而道只要有**一条**
 * 就永远不为空 —— 于是凝过道的人再也见不到这里的句子，只剩一条道时更是那句天天钉在扉页上
 * （`天 % 1 = 0`，连"轮换"都算不上）。排班让两边按天分场，池子不再被永久饿死。
 *
 * 为什么让道数参与：一条道时天天见会腻，所以它只占一个格；两条以上才占满上限。
 * 上限刻意不放到 `STARTUP_PERIOD`（= 独占），否则又回到"池子对有道的用户彻底消失"。
 * 页面还会对这两个量各做一次下限保护（周期 ≥ 1、道占格数 ≤ 周期 - 1），改坏也挤不掉池子。
 *
 * 取用这套数的是 `pages/entry/startup.vue`（排班属于"跟用户数据相关的挑法"，留在页面）。
 */
